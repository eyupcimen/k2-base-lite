// Generates src/styles/tokens.css and src/theme.tokens.json from scripts/tokens.json
// (copy of ~/Developer/DesignSystem/tokens.json). Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('./tokens.json', import.meta.url)));
const resolve = (theme, v) => (v.startsWith('{') ? t.color.tokens.find((x) => x.name === v.slice(1, -1)).value[theme] : v);
const colors = (theme) => t.color.tokens.map((c) => `  --${c.name}: ${resolve(theme, c.value[theme])};`).join('\n');
const type = t.type.groups.flatMap((g) => g.styles.map((s) => [
  `  --font-${s.name}-size: ${s.fontSize};`, `  --font-${s.name}-line: ${s.lineHeight};`, `  --font-${s.name}-weight: ${s.fontWeight};`,
  `  --font-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${g.family});`].join('\n'))).join('\n');
// Scene material colours (3D only; physical materials, theme-independent).
const scene = { 'pv-cell': '#1E3A6E', 'pv-frame': '#2B3138', 'rail-metal': '#C4CAD0', 'roof-tile': '#B9B2A6', 'grid-line': '#9AA19E', 'calib-marker': '#E8A317' };
const css = `/* GENERATED by scripts/gen-tokens.mjs from tokens.json. Do not edit. */
:root {
  color-scheme: light dark;
${colors('light')}
  --font-sans: ${t.type.families.sans};
  --font-mono: ${t.type.families.mono};
${type}
${t.spacing.tokens.map((s) => `  --${s.name}: ${s.value};`).join('\n')}
${t.radius.tokens.map((s) => `  --${s.name}: ${s.value};`).join('\n')}
  --stroke-1: 1px;
  --stroke-2: 2px;
  --control-height: 44px;
  --scene-min-height: 60vh;
  --scene-min-height-desktop: 75vh;
  --marker-size: 28px;
${Object.entries(scene).map(([k, v]) => `  --${k}: ${v};`).join('\n')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colors('dark').replace(/^/gm, '  ')}
  }
}
:root[data-theme="dark"] {
${colors('dark')}
}
`;
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);
const out = {};
for (const theme of ['light', 'dark']) out[theme] = Object.fromEntries(t.color.tokens.map((c) => [c.name, resolve(theme, c.value[theme])]));
out.scene = scene;
writeFileSync(new URL('../src/theme.tokens.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
console.log('tokens generated');
